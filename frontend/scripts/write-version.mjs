#!/usr/bin/env node
// 自動產生 src/app/core/version.ts，勿手動修改產出檔。
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

// 1. 讀取 version
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const version = pkg.version;

// 2. commit hash
let commit = process.env.WL_COMMIT ?? '';
if (!commit) {
  try {
    commit = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['pipe', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    commit = 'unknown';
  }
}
if (!commit) commit = 'unknown';

// 2b. 距離上一個版本標籤多少個提交（git describe；沒有標籤或不在 git 裡＝0）。頁首顯示成 v0.0.1+524，一眼看得出是標籤之後的第幾個提交。
let ahead = Number(process.env.WL_AHEAD ?? NaN);
if (Number.isNaN(ahead)) {
  try {
    const d = execSync('git describe --tags --long --match "v*"', { cwd: root, stdio: ['pipe', 'pipe', 'ignore'] }).toString().trim();
    const m = /-(\d+)-g[0-9a-f]+$/.exec(d);
    ahead = m ? Number(m[1]) : 0;
  } catch {
    ahead = 0;
  }
}

// 3. buildTime
const buildTime = process.env.WL_BUILD_TIME ?? new Date().toISOString();

// 4. 寫出 version.ts
const outDir = join(root, 'src/app/core');
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, 'version.ts');

const content = `// AUTO-GENERATED by scripts/write-version.mjs — 勿手動修改
// 每次 start／build／test 前自動覆寫，以 package.json version + git commit + buildTime 為準。這個檔不進版本庫。
export const versionInfo = {
  version: '${version}',
  buildTime: '${buildTime}',
  commit: '${commit}',
  /** 距離上一個版本標籤的提交數（0＝正好在標籤上）。 */
  ahead: ${ahead},
} as const;
`;

writeFileSync(outPath, content, 'utf8');
console.log(`[write-version] version=${version} ahead=${ahead} commit=${commit} buildTime=${buildTime}`);
console.log(`[write-version] written → ${outPath}`);

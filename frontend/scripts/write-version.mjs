#!/usr/bin/env node
// 自動產生 src/app/core/version.ts，勿手動修改產出檔。
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

// 1. 讀取 version
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const version = pkg.version;

// 2. commit hash
let commit = process.env.WL_COMMIT ?? '';
if (!commit) {
  try {
    commit = execSync('git rev-parse --short HEAD', { cwd: root, stdio: ['pipe', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    commit = 'unknown';
  }
}
if (!commit) commit = 'unknown';

// 3. buildTime
const buildTime = process.env.WL_BUILD_TIME ?? new Date().toISOString();

// 4. 寫出 version.ts
const outDir = join(root, 'src/app/core');
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, 'version.ts');

const content = `// AUTO-GENERATED by scripts/write-version.mjs — 勿手動修改
// 每次 build 前自動覆寫，以 package.json version + git commit + buildTime 為準。
export const versionInfo = {
  version: '${version}',
  buildTime: '${buildTime}',
  commit: '${commit}',
} as const;
`;

writeFileSync(outPath, content, 'utf8');
console.log(`[write-version] version=${version} commit=${commit} buildTime=${buildTime}`);
console.log(`[write-version] written → ${outPath}`);
